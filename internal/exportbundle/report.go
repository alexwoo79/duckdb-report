package exportbundle

import (
	"archive/zip"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

func ExportReport(reportDir, destination string, params map[string]string) error {
	includeReport := boolParam(params["include_report"], true)
	includeDatabase := boolParam(params["include_database"], true)
	includeSource := boolParam(params["include_source"], true)
	if !includeReport && !includeDatabase && !includeSource {
		return errors.New("export preset does not include any files")
	}
	if includeReport {
		found := false
		for _, name := range []string{"report.html", "report.pdf"} {
			if info, err := os.Stat(filepath.Join(reportDir, name)); err == nil && !info.IsDir() {
				found = true
				break
			}
		}
		if !found {
			return errors.New("report HTML or PDF output was not found")
		}
	}
	if includeDatabase {
		if info, err := os.Stat(filepath.Join(reportDir, "analysis.duckdb")); err != nil || info.IsDir() {
			return errors.New("report database snapshot was not found")
		}
	}
	file, err := os.Create(destination)
	if err != nil {
		return fmt.Errorf("create report package: %w", err)
	}
	archive := zip.NewWriter(file)
	add := func(name, source string) error {
		return addFile(archive, source, name)
	}
	if includeReport {
		for _, name := range []string{"report.html", "report.pdf"} {
			source := filepath.Join(reportDir, name)
			if info, statErr := os.Stat(source); statErr == nil && !info.IsDir() {
				if err := add(name, source); err != nil {
					archive.Close()
					file.Close()
					return err
				}
			}
		}
	}
	if includeDatabase {
		if err := add("analysis.duckdb", filepath.Join(reportDir, "analysis.duckdb")); err != nil {
			archive.Close()
			file.Close()
			return err
		}
	}
	if includeSource {
		if err := add("report.qmd", filepath.Join(reportDir, "report.qmd")); err != nil {
			archive.Close()
			file.Close()
			return err
		}
		assetRoot := filepath.Join(reportDir, "assets")
		if info, statErr := os.Stat(assetRoot); statErr == nil && info.IsDir() {
			if err := addDirectory(archive, assetRoot, "assets"); err != nil {
				archive.Close()
				file.Close()
				return err
			}
		}
	}
	readme, err := archive.Create("README.txt")
	if err != nil {
		archive.Close()
		file.Close()
		return fmt.Errorf("create package readme: %w", err)
	}
	_, _ = io.WriteString(readme, "Generated by DuckDB Report Studio\n\nThis package contains the report outputs selected by the workflow export node.\n")
	if err := archive.Close(); err != nil {
		file.Close()
		return fmt.Errorf("close report package: %w", err)
	}
	if err := file.Close(); err != nil {
		return fmt.Errorf("close report package file: %w", err)
	}
	return nil
}

func boolParam(value string, defaultValue bool) bool {
	if strings.TrimSpace(value) == "" {
		return defaultValue
	}
	parsed, err := strconv.ParseBool(value)
	if err != nil {
		return defaultValue
	}
	return parsed
}

func addDirectory(archive *zip.Writer, root, prefix string) error {
	return filepath.WalkDir(root, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return fmt.Errorf("walk report package assets: %w", walkErr)
		}
		if entry.IsDir() {
			return nil
		}
		if !entry.Type().IsRegular() {
			return nil
		}
		relative, err := filepath.Rel(root, path)
		if err != nil {
			return fmt.Errorf("resolve report package asset: %w", err)
		}
		return addFile(archive, path, prefix+"/"+filepath.ToSlash(relative))
	})
}

func addFile(archive *zip.Writer, source, name string) error {
	input, err := os.Open(source)
	if err != nil {
		return fmt.Errorf("open report package source: %w", err)
	}
	defer input.Close()
	info, err := input.Stat()
	if err != nil {
		return fmt.Errorf("inspect report package source: %w", err)
	}
	header, err := zip.FileInfoHeader(info)
	if err != nil {
		return fmt.Errorf("create report package entry: %w", err)
	}
	header.Name = filepath.ToSlash(name)
	header.Method = zip.Deflate
	output, err := archive.CreateHeader(header)
	if err != nil {
		return fmt.Errorf("create report package entry: %w", err)
	}
	if _, err := io.Copy(output, input); err != nil {
		return fmt.Errorf("write report package file: %w", err)
	}
	return nil
}
